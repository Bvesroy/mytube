"""Ask My Tube (Feature 2): private RAG over the user's own library.

Retrieval is hybrid: FTS5 transcripts + knowledge extracts, plus local embedding
similarity. Results are fused with reciprocal-rank fusion, then reranked with a
small lexical overlap bonus. Every citation is built from a retrieved database row;
timestamps are passed through from the stored segment and stay `None` when the
transcript has no trustworthy timing.

The optional local LLM only writes prose over those numbered sources. Its answer is
accepted only when every citation marker points at a supplied source; otherwise the
deterministic extractive answer is returned instead. No source, quote, timestamp or
video id is ever generated by the model.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from typing import Any

from sqlalchemy import select
from sqlalchemy import text as sql_text
from sqlalchemy.orm import Session

from app.db.models import Channel, Concept, KnowledgeExtract, Transcript, TranscriptSegment, Video
from app.services.ai.provider import AIUnavailable, LocalLLM
from app.services.knowledge.index import semantic_search
from app.services.knowledge.text import (
    excerpt,
    fts_query,
    normalize_text,
    split_sentences,
    words,
)
from app.services.knowledge.transcripts import search_library_transcripts
from app.services.search import search_videos

RRF_K = 60


@dataclass
class Source:
    key: str
    video_id: str
    title: str
    channel: str
    text: str
    start_s: float | None
    source_kind: str
    score: float = 0.0
    methods: list[str] = field(default_factory=list)
    extract_id: int | None = None
    segment_id: int | None = None

    def citation(self, index: int, max_score: float) -> dict[str, Any]:
        relevance = round(min(1.0, self.score / max_score), 3) if max_score > 0 else 0.0
        label = "high" if relevance >= 0.66 else "medium" if relevance >= 0.33 else "low"
        return {
            "index": index,
            "video_id": self.video_id,
            "title": self.title,
            "channel": self.channel,
            "timestamp_s": self.start_s,
            "excerpt": excerpt(self.text, "", width=320),
            "source_kind": self.source_kind,
            "methods": sorted(set(self.methods)),
            "relevance": relevance,
            "relevance_label": label,
            "extract_id": self.extract_id,
            "segment_id": self.segment_id,
        }


def _video_meta(session: Session, video_ids: list[int]) -> dict[int, tuple[str, str, str]]:
    if not video_ids:
        return {}
    rows = session.execute(
        select(Video.id, Video.yt_id, Video.title, Channel.name)
        .outerjoin(Channel, Channel.id == Video.channel_id)
        .where(Video.id.in_(video_ids))
    ).all()
    return {int(r[0]): (r[1] or "", r[2] or "", r[3] or "") for r in rows}


def _knowledge_hits(session: Session, query: str, *, limit: int = 30) -> list[dict[str, Any]]:
    match = fts_query(query)
    if not match:
        return []
    rows = session.execute(
        sql_text(
            """
            SELECT e.id, e.content, e.detail, e.start_s, e.kind,
                   v.yt_id, v.title, coalesce(c.name,'') AS channel_name,
                   bm25(knowledge_fts) AS rank
              FROM knowledge_fts
              JOIN knowledge_extracts e ON e.id = knowledge_fts.rowid
              JOIN videos v ON v.id = e.video_id
              LEFT JOIN channels c ON c.id = v.channel_id
             WHERE knowledge_fts MATCH :match AND e.rejected = 0
             ORDER BY rank
             LIMIT :limit
            """
        ),
        {"match": match, "limit": limit},
    ).fetchall()
    return [dict(row._mapping) for row in rows]


def _segment_rows(session: Session, ids: list[int]) -> dict[int, Any]:
    if not ids:
        return {}
    rows = session.execute(
        select(
            TranscriptSegment.id,
            TranscriptSegment.text,
            TranscriptSegment.start_s,
            TranscriptSegment.transcript_id,
        ).where(TranscriptSegment.id.in_(ids))
    ).all()
    return {int(r[0]): r for r in rows}


def _transcript_video_map(session: Session, transcript_ids: list[int]) -> dict[int, tuple[str, str, str, str]]:
    if not transcript_ids:
        return {}
    rows = session.execute(
        select(
            Transcript.id,
            Video.yt_id,
            Video.title,
            Channel.name,
            Transcript.timing_source,
        )
        .join(Transcript, Transcript.video_id == Video.id)
        .outerjoin(Channel, Channel.id == Video.channel_id)
        .where(Transcript.id.in_(transcript_ids))
    ).all()
    return {
        int(r[0]): (r[1] or "", r[2] or "", r[3] or "", r[4] or "none") for r in rows
    }


def retrieve(session: Session, question: str, *, limit: int = 8, pool: int = 40) -> list[Source]:
    sources: dict[str, Source] = {}

    def add(key: str, source: Source, rank: int | None, method: str, semantic_score: float = 0.0) -> None:
        existing = sources.get(key)
        if existing is None:
            existing = source
            sources[key] = existing
        if method not in existing.methods:
            existing.methods.append(method)
        if rank is not None:
            existing.score += 1.0 / (RRF_K + rank + 1)
        if semantic_score:
            existing.score += semantic_score * 0.6
        # Keep the richer text between duplicate rows.
        if len(source.text) > len(existing.text):
            existing.text = source.text

    # 1. Transcript lexical retrieval.
    for rank, hit in enumerate(search_library_transcripts(session, question, limit=pool)):
        add(
            f"segment:{hit.segment_id}",
            Source(
                key=f"segment:{hit.segment_id}",
                video_id=hit.video_id,
                title=hit.video_title,
                channel=hit.channel_name,
                text=hit.text,
                start_s=hit.start_s,
                source_kind="transcript",
                segment_id=hit.segment_id,
            ),
            rank,
            "fts_transcript",
        )

    # 2. Extracted-knowledge lexical retrieval.
    for rank, row in enumerate(_knowledge_hits(session, question, limit=pool)):
        body = " ".join(p for p in [str(row["content"]), str(row["detail"] or "")] if p)
        add(
            f"extract:{row['id']}",
            Source(
                key=f"extract:{row['id']}",
                video_id=str(row["yt_id"]),
                title=str(row["title"] or ""),
                channel=str(row["channel_name"] or ""),
                text=body,
                start_s=float(row["start_s"]) if row["start_s"] is not None else None,
                source_kind=str(row["kind"]),
                extract_id=int(row["id"]),
            ),
            rank,
            "fts_knowledge",
        )

    # 3. Video lexical retrieval (title/description) keeps whole-video answers possible.
    try:
        hits, _cursor, _count = search_videos(session, question, limit=min(20, pool))
    except Exception:  # pragma: no cover - FTS missing on a damaged DB
        hits = []
    internal_ids = []
    for hit in hits:
        try:
            internal_ids.append(int(hit.id))
        except (TypeError, ValueError):
            continue
    meta = _video_meta(session, internal_ids)
    for rank, hit in enumerate(hits):
        try:
            internal = int(hit.id)
        except (TypeError, ValueError):
            continue
        info = meta.get(internal)
        if not info:
            continue
        yt_id, title, channel = info
        add(
            f"video:{yt_id}",
            Source(
                key=f"video:{yt_id}",
                video_id=yt_id,
                title=title,
                channel=channel,
                text=f"{title}. {hit.snippet or ''}".strip(),
                start_s=None,
                source_kind="video_metadata",
            ),
            rank,
            "fts_video",
        )

    # 4. Local semantic retrieval over stored vectors, balanced per owner type.
    try:
        semantic_items: list[dict[str, Any]] = []
        for owner_type in ("video", "extract", "segment"):
            semantic_items.extend(
                semantic_search(session, question, owner_types=(owner_type,), limit=12)
            )
        qterms_early = {w for w in words(question) if len(w) > 2}
        for rank, item in enumerate(semantic_items):
            # Weak semantic matches on unrelated text are not evidence.
            if item["score"] < 0.22:
                owner_text = ""
                if item["owner_type"] == "extract":
                    row = session.get(KnowledgeExtract, item["owner_id"])
                    owner_text = f"{row.content} {row.detail or ''}" if row else ""
                elif item["owner_type"] == "video":
                    row = session.get(Video, item["owner_id"])
                    owner_text = f"{row.title} {row.description or ''}" if row else ""
                elif item["owner_type"] == "segment":
                    row = session.get(TranscriptSegment, item["owner_id"])
                    owner_text = row.text if row else ""
                overlap = len(qterms_early & set(words(owner_text))) / max(1, len(qterms_early))
                if overlap < 0.5:
                    continue
            owner_type = item["owner_type"]
            if owner_type == "video":
                rows = session.execute(
                    select(Video.yt_id, Video.title, Channel.name)
                    .outerjoin(Channel, Channel.id == Video.channel_id)
                    .where(Video.id == item["owner_id"])
                ).first()
                if not rows:
                    continue
                add(
                    f"video:{rows[0]}",
                    Source(
                        key=f"video:{rows[0]}",
                        video_id=rows[0],
                        title=rows[1] or "",
                        channel=rows[2] or "",
                        text=f"{rows[1]}. {session.get(Video, item['owner_id']).description or ''}".strip()[:900],
                        start_s=None,
                        source_kind="video_metadata",
                    ),
                    rank,
                    "semantic_video",
                    item["score"],
                )
            elif owner_type == "extract":
                row = session.get(KnowledgeExtract, item["owner_id"])
                if row is None or row.rejected:
                    continue
                video = session.get(Video, row.video_id)
                if video is None:
                    continue
                ch = session.get(Channel, video.channel_id) if video.channel_id else None
                add(
                    f"extract:{row.id}",
                    Source(
                        key=f"extract:{row.id}",
                        video_id=video.yt_id,
                        title=video.title,
                        channel=ch.name if ch else "",
                        text=" ".join(p for p in [row.content, row.detail or ""] if p),
                        start_s=row.start_s,
                        source_kind=row.kind,
                        extract_id=row.id,
                    ),
                    rank,
                    "semantic_extract",
                    item["score"],
                )
            elif owner_type == "segment":
                seg = session.get(TranscriptSegment, item["owner_id"])
                if seg is None:
                    continue
                tr = session.get(Transcript, seg.transcript_id)
                if tr is None:
                    continue
                video = session.get(Video, tr.video_id)
                if video is None:
                    continue
                ch = session.get(Channel, video.channel_id) if video.channel_id else None
                add(
                    f"segment:{seg.id}",
                    Source(
                        key=f"segment:{seg.id}",
                        video_id=video.yt_id,
                        title=video.title,
                        channel=ch.name if ch else "",
                        text=seg.text,
                        start_s=float(seg.start_s) if (tr.timing_source or "none") == "supplied" else None,
                        source_kind="transcript",
                        segment_id=seg.id,
                    ),
                    rank,
                    "semantic_segment",
                    item["score"],
                )
    except Exception:
        # Semantic retrieval is an enhancement; lexical/FTS answers must still work.
        pass

    # 5. Rerank: small bonus for query-term overlap, then score.
    qterms = {w for w in words(question) if len(w) > 2}
    for source in sources.values():
        if qterms:
            sterms = set(words(source.text))
            overlap = len(qterms & sterms) / max(1, len(qterms))
            source.score += overlap * 0.35
        if source.source_kind == "transcript":
            source.score += 0.08
        elif source.source_kind == "video_metadata":
            source.score -= 0.05
    ranked = sorted(sources.values(), key=lambda s: (-s.score, s.video_id, s.start_s or 0))
    return ranked[:limit]


def matched_concepts(session: Session, question: str, *, limit: int = 6) -> list[dict[str, Any]]:
    tokens = [w for w in words(question) if len(w) > 2]
    if not tokens:
        return []
    rows = session.scalars(select(Concept).limit(5000)).all()
    scored = []
    for concept in rows:
        name = concept.name.lower()
        hits = sum(1 for token in tokens if token in name)
        if hits:
            scored.append((hits, concept))
    scored.sort(key=lambda item: (-item[0], item[1].name))
    return [
        {"name": c.name, "slug": c.slug, "confidence": min(0.9, 0.3 + 0.2 * hits)}
        for hits, c in scored[:limit]
    ]


def _extractive_answer(question: str, citations: list[dict[str, Any]]) -> str:
    if not citations:
        return (
            "I couldn't find evidence for that in your imported subscriptions. "
            "No matching transcript segments or extracted knowledge were stored, so I "
            "won't guess. Try a broader question or process more videos."
        )
    lines = ["Here is what your library actually contains, with sources:", ""]
    for cite in citations[:5]:
        text = cite["excerpt"]
        sentences = split_sentences(text)
        if sentences:
            qterms = {w for w in words(question) if len(w) > 2}
            best = max(
                sentences,
                key=lambda s: len(qterms & set(words(s.text))) + (0.1 if s.text else 0),
            )
            text = best.text
        stamp = (
            f" @ {_fmt_ts(cite['timestamp_s'])}"
            if cite.get("timestamp_s") is not None
            else ""
        )
        lines.append(f"- {text} [{cite['index']}] — {cite['title']}{stamp}")
    lines.append("")
    lines.append(
        "These are excerpts from your own indexed videos. I did not add outside knowledge."
    )
    return "\n".join(lines)


def _fmt_ts(value: float) -> str:
    total = int(value)
    hours, rem = divmod(total, 3600)
    minutes, seconds = divmod(rem, 60)
    if hours:
        return f"{hours}:{minutes:02d}:{seconds:02d}"
    return f"{minutes}:{seconds:02d}"


def _llm_prompt(question: str, citations: list[dict[str, Any]]) -> str:
    blocks = []
    for cite in citations:
        stamp = (
            f" at {_fmt_ts(cite['timestamp_s'])}"
            if cite.get("timestamp_s") is not None
            else ""
        )
        blocks.append(
            f"[{cite['index']}] {cite['title']} ({cite['channel']}){stamp}\n"
            f"{cite['excerpt']}"
        )
    return (
        "Answer the question using ONLY the numbered sources below. "
        "Cite every factual sentence with [n]. If the sources do not answer it, say "
        '"The library does not contain enough evidence." Do not use outside knowledge, '
        "do not invent videos, quotes or timestamps.\n\n"
        f"QUESTION: {question}\n\nSOURCES:\n" + "\n\n".join(blocks)
    )


def _valid_llm_answer(answer: str, count: int) -> bool:
    if len(answer.strip()) < 10:
        return False
    refs = [int(x) for x in re.findall(r"\[(\d+)\]", answer)]
    if not refs:
        return False
    return all(1 <= ref <= count for ref in refs)


def ask(
    session: Session,
    question: str,
    *,
    limit: int = 8,
    use_llm: bool = False,
    llm: LocalLLM | None = None,
) -> dict[str, Any]:
    question = normalize_text(question)
    if not question:
        raise ValueError("question required")
    ranked = retrieve(session, question, limit=limit)
    max_score = max((s.score for s in ranked), default=0.0)
    citations = [s.citation(i + 1, max_score) for i, s in enumerate(ranked)]
    concepts = matched_concepts(session, question)

    mode = "extractive"
    notes: list[str] = []
    answer = _extractive_answer(question, citations)
    if use_llm and citations:
        provider = llm or LocalLLM.detect()
        if provider.available:
            try:
                candidate = provider.generate(_llm_prompt(question, citations), max_tokens=500, temperature=0.1)
                if _valid_llm_answer(candidate, len(citations)):
                    answer = candidate
                    mode = "llm"
                else:
                    notes.append(
                        "Local model answer rejected: it did not cite supplied sources, so the "
                        "extractive answer is shown."
                    )
            except AIUnavailable as exc:
                notes.append(f"Local model unavailable: {exc}. Extractive answer shown.")
        else:
            notes.append("No local model available; extractive answer shown.")
    elif use_llm and not citations:
        notes.append("No sources retrieved, so no model call was made.")

    return {
        "question": question,
        "answer": answer,
        "mode": mode,
        "sufficient_evidence": bool(citations),
        "citations": citations,
        "matched_concepts": concepts,
        "retrieval": {
            "sources_considered": len(ranked),
            "methods": sorted({m for s in ranked for m in s.methods}),
            "note": "Citations come from stored transcripts/extracts or video metadata only.",
        },
        "notes": notes,
    }
